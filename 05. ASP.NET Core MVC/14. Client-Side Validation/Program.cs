using Microsoft.AspNetCore.Builder;
using Microsoft.Extensions.DependencyInjection;

/*
 * SECTION 1: HOW UNOBTRUSIVE VALIDATION WORKS
 *
 * Pipeline summary:
 *
 *   [DataAnnotation on model property]
 *         │
 *         ▼  (Tag Helper / HtmlHelper renders the <input>)
 *   data-val="true"  data-val-required="The field is required."
 *         │
 *         ▼  (jquery.validate.unobtrusive scans the DOM at document-ready)
 *   $.validator.unobtrusive.parse(form)   ← reads data-val-* attrs, calls
 *         │                                  $.validator.addRule() internally
 *         ▼
 *   jquery.validate.js validates the field on blur / keyup / submit
 *         │
 *         ▼  (unobtrusive writes the error into the matching span)
 *   <span data-valmsg-for="FieldName">The field is required.</span>
 *
 * Key components:
 *   jquery.js                      — base DOM / event library
 *   jquery.validate.js             — core validation engine (rules, messages, methods)
 *   jquery.validate.unobtrusive.js — bridge: reads data-val-* attrs → calls validate API
 *
 * Load ORDER matters — each script depends on the one above it in the list.
 * jQuery must be in the layout; the other two go in _ValidationScriptsPartial (per-page).
 *
 * Server fallback:
 *   Client-side validation can be bypassed (JS disabled, Postman, curl).
 *   Always check ModelState.IsValid in POST actions — Section 5 covers this.
 *
 * Data attributes on a rendered <input>:
 *   data-val="true"                  ← triggers unobtrusive parsing for this element
 *   data-val-required="..."          ← [Required]
 *   data-val-length="..."            ← [StringLength]
 *   data-val-length-max="50"
 *   data-val-length-min="3"
 *   data-val-range="..."             ← [Range]
 *   data-val-range-min="18"
 *   data-val-range-max="120"
 *   data-val-regex="..."             ← [RegularExpression]
 *   data-val-regex-pattern="..."
 *   data-val-equalto="..."           ← [Compare]
 *   data-val-equalto-other="..."
 *   data-val-email="..."             ← [EmailAddress]
 *
 * Span attributes rendered by asp-validation-for:
 *   data-valmsg-for="FieldName"      ← identifies which field's error to display
 *   data-valmsg-replace="true"       ← unobtrusive replaces the span text on error
 *
 * Div attributes rendered by asp-validation-summary:
 *   data-valmsg-summary="true"       ← aggregates all field errors into the div
 */

