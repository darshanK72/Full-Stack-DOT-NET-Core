app.Run();

/*
 * QUICK REFERENCE — Client-Side Validation
 *
 * Three script delivery options (choose one per project):
 *   CDN:    <script src="https://cdnjs.cloudflare.com/ajax/libs/...">
 *   LibMan: libman.json → restores to wwwroot/lib; <script src="~/lib/...">
 *   Bundle: bundleconfig.json + BuildBundlerMinifier NuGet pkg; <script src="~/bundles/...">
 *
 * Enabling/disabling unobtrusive validation at page level:
 *   $.validator.setDefaults({ ignore: "" });  // validate hidden fields too
 *   $.validator.unobtrusive.options = { ... };
 *
 * Re-parse after AJAX-injected HTML (dynamic DOM):
 *   $.validator.unobtrusive.parse("#myForm");   // re-read data-val-* for new fields
 *   // or pass a container element:
 *   $.validator.unobtrusive.parse($(".dynamic-section"));
 *
 * Custom validator registration pattern:
 *   jQuery.validator.addMethod("rulename", function(value, element, params) { ... });
 *   $.validator.unobtrusive.adapters.addBool("rulename");       // no extra params
 *   $.validator.unobtrusive.adapters.addSingleVal("rulename", "paramname"); // 1 param
 *   $.validator.unobtrusive.adapters.addMinMax("rulename", "minrule", "maxrule", "min", "max");
 *   $.validator.unobtrusive.adapters.add("rulename", ["p1","p2"], function(opts) { ... });
 *
 * IClientModelValidator interface:
 *   void AddValidation(ClientModelValidationContext context)
 *   context.Attributes — IDictionary<string, string>; add "data-val-*" keys here
 *   MergeAttribute helper: only adds if key is not already present
 *
 * ModelState on the server is always the authority — never skip server validation.
 */
